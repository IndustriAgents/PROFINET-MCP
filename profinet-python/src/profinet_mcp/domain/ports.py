from __future__ import annotations

from typing import Any, Protocol


class ProfinetClientPort(Protocol):
    config: Any

    def backend_name(self) -> Any: ...

    async def discover_devices(self, timeout: Any = ..., *, allow_cached: Any = ...) -> Any: ...

    async def find_device(self, identifier: Any, timeout: Any = ...) -> Any: ...

    async def read_io_data(self, device_name: Any, slot: Any, subslot: Any, length: Any) -> Any: ...

    async def write_io_data(self, device_name: Any, slot: Any, subslot: Any, data: Any) -> Any: ...

    async def identify_device(self, device_mac: Any, duration_s: Any) -> Any: ...

    async def set_device_name(self, device_mac: Any, name: Any) -> Any: ...

    async def set_device_ip(self, device_mac: Any, ip_address: Any, subnet_mask: Any, gateway: Any) -> Any: ...

    def connection_status(self) -> Any: ...

    def shutdown(self) -> Any: ...

    async def probe(self) -> Any: ...
